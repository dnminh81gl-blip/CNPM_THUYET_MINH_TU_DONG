function curLang() { try { return Settings.get().lang || "vi"; } catch (e) { return "vi"; } }
function t(key, vars) {
  const L = curLang();
  let s = (I18N[L] && I18N[L][key] != null) ? I18N[L][key] : (I18N.vi[key] != null ? I18N.vi[key] : key);
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
  return s;
}
function tv(vi) {
  const L = curLang(); if (L === "vi" || vi == null) return vi;
  const d = I18N_DATA[String(vi)] || I18N_DATA[String(vi).trim()];
  return d && d[L] ? d[L] : vi;
}

